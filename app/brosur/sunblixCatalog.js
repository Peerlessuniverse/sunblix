    sub: `${pkg.category} • ${pkg.panelsCount} Modul • ${pkg.phase} • Rp ${pkg.price.toLocaleString('id-ID')}`,
    docNo: docNo,
    sphCode: sphCode,
    date: '01 Oktober 2026',
